"""Generate top-to-bottom 400x300 BWRY screens and the setup text font."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'firmware/main/assets'
PALETTE = [(0, 0, 0), (255, 255, 255), (255, 255, 0), (255, 0, 0)]

def font(size):
    return ImageFont.load_default(size=size)

def page():
    im = Image.new('RGB', (400, 300), 'white')
    d = ImageDraw.Draw(im)
    d.text((156, 22), 'Tesserae', font=font(22), fill='black')
    d.text((156, 49), 'ZecTrix NOTE4C Devkit', font=font(12), fill='black')
    return im, d

def pack(im):
    values = [min(range(4), key=lambda i: sum((p[c]-PALETTE[i][c])**2 for c in range(3))) for p in im.get_flattened_data()]
    return bytes((values[i]<<6)|(values[i+1]<<4)|(values[i+2]<<2)|values[i+3] for i in range(0,len(values),4))

def write(name, im):
    data = pack(im)
    assert len(data) == 30000
    (OUT / (name+'.bin')).write_bytes(data)

OUT.mkdir(exist_ok=True)
im,d=page()
d.text((156,78),'Wi-Fi setup',font=font(29),fill='black')
d.text((156,124),'NETWORK',font=font(12),fill='red')
d.text((156,173),'PASSWORD',font=font(12),fill='red')
d.text((16,231),'Scan the QR code or join this Wi-Fi.',font=font(18),fill='black')
d.text((16,260),'Then open 192.168.4.1',font=font(18),fill='black')
write('splash_setup',im)
for name,title,lines,color in [
    ('lowbatt','Battery low',['Please connect','a charger.'],'red'),
    ('waiting','Connected',['Waiting for your','first picture.'],'black'),
    ('register','Register device',['Open Tesserae:','Settings > Devices'],'black'),
    ('revoked','Unpaired',['Hold front button','for 20 seconds','to open setup.'],'black')]:
    im,d=page(); d.rectangle((0,0,128,299),fill=color)
    if name=='lowbatt':
        d.rounded_rectangle((23,125,99,170),radius=6,outline='white',width=5)
        d.rectangle((102,139,109,156),fill='white')
        d.rectangle((32,134,45,161),fill='white')
    else:
        d.ellipse((28,115,98,185),outline='white',width=4)
        d.line([(44,150),(58,164),(84,134)],fill='white',width=6)
    d.text((156,105),title,font=font(29 if name!='register' else 26),fill='black')
    d.rectangle((156,149,232,153),fill=color if name=='lowbatt' else 'yellow')
    for y,line in zip((174,201,228),lines): d.text((156,y),line,font=font(20),fill='black')
    if name=='lowbatt': d.text((156,258),'Press front to check charge.',font=font(14),fill='black')
    write('splash_'+name,im)

lines=['// SPDX-License-Identifier: AGPL-3.0-or-later', '// Copyright (C) 2026 varanu5 <https://github.com/varanu5>', '// Generated by tools/gen_assets.py.', '#pragma once', '#include <stdint.h>',
       'static const struct { uint8_t advance; uint32_t rows[24]; } setup_font[95] = {']
for code in range(32,127):
    im=Image.new('1',(24,24)); d=ImageDraw.Draw(im); d.text((0,0),chr(code),font=font(19),fill=1)
    rows=[sum(int(bool(im.getpixel((x,y))))<<x for x in range(24)) for y in range(24)]
    lines.append('    {%d, {%s}},' % (round(d.textlength(chr(code),font=font(19))), ','.join(hex(r) for r in rows)))
lines.append('};')
(ROOT/'firmware/main/setup_font.h').write_text('\n'.join(lines)+'\n')
print('Generated five 30,000-byte screens and setup font.')
